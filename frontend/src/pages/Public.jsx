import React, { useState } from 'react';
import { Link, Navigate, useNavigate } from 'react-router-dom';
import { useAuth } from '../auth.jsx';
import { api } from '../api';
import { ErrorBox, Field, PageHead, useAsync } from '../components/ui.jsx';

export function Login() {
  const { user, login } = useAuth();
  const nav = useNavigate();
  const [id, setId] = useState('');
  const [pw, setPw] = useState('');
  const [err, setErr] = useState(null);
  const [busy, setBusy] = useState(false);
  const setup = useAsync(() => api.get('/api/auth/setup-status').catch(() => ({ needs_setup: false })), []);
  if (user) return <Navigate to="/" replace />;
  const submit = async (e) => {
    e.preventDefault(); setErr(null); setBusy(true);
    try { await login(id, pw); nav('/'); } catch (x) { setErr(x); } finally { setBusy(false); }
  };
  return (
    <div className="loginwrap">
      <form className="loginbox" onSubmit={submit} noValidate>
        <h1>Student Result Management System</h1>
        <p className="muted">Sign in with your user ID and password. Students, faculty and administrators use the same page.</p>
        <ErrorBox error={err} />
        <Field label="User ID" id="uid"><input id="uid" autoComplete="username" value={id} onChange={(e) => setId(e.target.value)} autoFocus required /></Field>
        <Field label="Password" id="pw"><input id="pw" type="password" autoComplete="current-password" value={pw} onChange={(e) => setPw(e.target.value)} required /></Field>
        <button className="btn" disabled={busy || !id || !pw}>{busy ? 'Signing in...' : 'Sign in'}</button>
        {setup.data && setup.data.needs_setup && <p className="small" style={{ marginTop: '1rem' }}><Link to="/setup">Set up the first administrator</Link></p>}
        <p className="legal">By signing in you accept the <Link to="/terms">Terms of Service</Link> and the <Link to="/privacy">Privacy Policy</Link>.</p>
      </form>
    </div>
  );
}

export function Setup() {
  const [f, setF] = useState({ token: '', login_id: '', full_name: '', password: '' });
  const [err, setErr] = useState(null);
  const [done, setDone] = useState(false);
  const set = (k) => (e) => setF({ ...f, [k]: e.target.value });
  const submit = async (e) => {
    e.preventDefault(); setErr(null);
    try { await api.post('/api/auth/setup', f); setDone(true); } catch (x) { setErr(x); }
  };
  return (
    <div className="loginwrap">
      <form className="loginbox" onSubmit={submit}>
        <h1>First administrator</h1>
        {done ? <><div className="alert ok">Administrator created. Remove SETUP_TOKEN from the server settings now.</div><Link className="btn" to="/login">Go to sign in</Link></> : (
          <>
            <p className="muted">This page works only while no administrator exists and the server has a setup token configured.</p>
            <ErrorBox error={err} />
            <Field label="Setup token" id="t"><input id="t" type="password" value={f.token} onChange={set('token')} required /></Field>
            <Field label="Login ID" id="l"><input id="l" value={f.login_id} onChange={set('login_id')} required /></Field>
            <Field label="Full name" id="n"><input id="n" value={f.full_name} onChange={set('full_name')} required /></Field>
            <Field label="Password" id="p" hint="At least 8 characters"><input id="p" type="password" value={f.password} onChange={set('password')} required /></Field>
            <button className="btn">Create administrator</button>
          </>
        )}
      </form>
    </div>
  );
}

