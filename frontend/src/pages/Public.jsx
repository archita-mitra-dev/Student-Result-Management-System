export function Account() {
  const [f, setF] = useState({ current_password: '', new_password: '' });
  const [err, setErr] = useState(null);
  const [ok, setOk] = useState(false);
  const submit = async (e) => {
    e.preventDefault(); setErr(null); setOk(false);
    try { await api.post('/api/auth/change-password', f); setOk(true); setF({ current_password: '', new_password: '' }); } catch (x) { setErr(x); }
  };
  return (
    <>
      <PageHead title="Change password" />
      <form className="panel" style={{ maxWidth: 420 }} onSubmit={submit}>
        <ErrorBox error={err} />
        {ok && <div className="alert ok">Password changed.</div>}
        <Field label="Current password" id="c"><input id="c" type="password" autoComplete="current-password" value={f.current_password} onChange={(e) => setF({ ...f, current_password: e.target.value })} required /></Field>
        <Field label="New password" id="n" hint="At least 8 characters"><input id="n" type="password" autoComplete="new-password" value={f.new_password} onChange={(e) => setF({ ...f, new_password: e.target.value })} required /></Field>
        <button className="btn">Change password</button>
      </form>
    </>
  );
}
